import { existsSync, readFileSync, readdirSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { CARDS as HIGHER } from '../components/MarkBank/cards/maths/higher';
import { CARDS as ORDINARY } from '../components/MarkBank/cards/maths/ordinary';
import { CARDS as FOUNDATION } from '../components/MarkBank/cards/maths/foundation';
import { browseTopicIdsForQuestion, questionsForTopics, topicsForPaper } from '../components/PaperTrail/topics';
import { PAPER_TRAIL_INDEX } from '../paperTrailData';
import { isAnswerMap, preferredAnswersUrl } from '../components/PaperTrail/vaultResolve';
import { paperRegionFor, schemeRegionFor } from '../components/PaperTrail/paperRegion';
import type { PaperAnswerMap, PaperLevel } from '../types/paperTrail';
import alternatives from '../scripts/markbank/mathematics/historical-alternative-anchors.json';

interface Review {
  year: number;
  level: PaperLevel;
  lang: 'ev';
  paperFileid: string;
  schemeFileid: string;
  paperKey: string;
  cards: {
    id: string;
    totalMarks: number;
    topicId: string;
    sourcePages: number[];
    schemePages: number[];
    printedParts: string[];
    atlasQuestionNumber?: string;
    examTopicIds: string[];
  }[];
}

// These ledgers record the independent page-by-page paper/scheme reviews.
// Counts alone, including a count generated by the authoring parser, are not
// evidence of completeness. This check reconciles those reviews to the actual
// indexed booklets, published cards and student-facing Atlas browse results.
const directory = 'scripts/markbank/mathematics/reviews';
const reviews: Review[] = readdirSync(directory).filter(name => name.endsWith('.json'))
  .map(name => JSON.parse(readFileSync(`${directory}/${name}`, 'utf8')));
const cards = [...HIGHER, ...ORDINARY, ...FOUNDATION];
const feeds = new Map<string, Set<string>>();
const identity = (year: number, fileid: string, n = '') => `${year}|${fileid}|${n}`;

describe('2010–2026 English-language Mathematics scope', () => {
  it('reconciles every indexed English booklet and every published card exactly once', () => {
    const indexed = PAPER_TRAIL_INDEX.mathematics
      .filter(entry => entry.lang === 'ev' && entry.year >= 2010 && entry.year <= 2026)
      .flatMap(entry => entry.papers.map(paper => identity(entry.year, paper.doc.f)));
    const reviewed = reviews.map(review => identity(review.year, review.paperFileid));
    expect(new Set(indexed).size).toBe(indexed.length);
    expect(new Set(reviewed).size).toBe(reviewed.length);
    expect(reviewed.sort()).toEqual(indexed.sort());
    const reviewedIds = reviews.flatMap(review => review.cards.map(card => card.id));
    expect(new Set(reviewedIds).size).toBe(reviewedIds.length);
    expect(cards.map(card => card.id).sort()).toEqual(reviewedIds.sort());
  });

  for (const review of reviews) {
    it(`${review.year}/${review.paperFileid}: retains the reviewed tasks in Mark Bank and Topic Atlas`, () => {
      const published = cards.filter(card => card.year === review.year
        && card.sourceMaterial?.sourceFileid === review.paperFileid);
      expect(published.map(card => card.id).sort()).toEqual(review.cards.map(card => card.id).sort());
      const paper = topicsForPaper('mathematics', review.year, review.level, 'ev', review.paperFileid)!;
      expect(paper).not.toBeNull();
      const committed = `scripts/paper-trail/answers/${review.year}/${review.paperFileid}.json`;
      const url = preferredAnswersUrl('mathematics', review.year, review.paperFileid, committed);
      const answerPath = url.startsWith('/') ? 'public' + url : url;
      const anchorsPath = `public/paper-anchors/${review.year}/${review.paperFileid}.json`;
      const map: PaperAnswerMap = JSON.parse(readFileSync(existsSync(answerPath) ? answerPath : anchorsPath, 'utf8'));
      expect(isAnswerMap(map)).toBe(true);
      expect(map.paperFileid).toBe(review.paperFileid);
      if (url.startsWith('/')) {
        expect(readFileSync(answerPath, 'utf8')).toBe(readFileSync(committed, 'utf8'));
        expect(map.schemeFileid).toBe(review.schemeFileid);
      }
      const repairedAlternatives = alternatives.papers.find(item => item.year === review.year
        && item.paperFileid === review.paperFileid)?.questions;
      for (const task of review.cards) {
        const card = published.find(candidate => candidate.id === task.id)!;
        expect(card.totalMarks, task.id).toBe(task.totalMarks);
        expect(card.topicId, task.id).toBe(task.topicId);
        expect(card.sourceMaterial?.pages, task.id).toEqual(task.sourcePages);
        const n = task.atlasQuestionNumber ?? task.printedParts[0].match(/^Q(\d+[A-Z]?)/)![1];
        const question = paper.q.find(candidate => candidate.n === n)!;
        expect(question, task.id).toBeDefined();
        const anchor = map.q.find(candidate => candidate.n === n)!;
        expect(anchor, `${task.id}: exact Atlas question anchor`).toBeDefined();
        const wholeMapRestored = review.year === 2012
          && ['LC003GLP200EV.pdf', 'LC003BLP230EV.pdf'].includes(review.paperFileid);
        if (wholeMapRestored || review.paperFileid.includes('-deferred')
          || (repairedAlternatives && n in repairedAlternatives)) {
          expect(url, task.id).toBe(`/paper-answers/${review.year}/${review.paperFileid}.json`);
          // Legacy maps may intentionally open the full paper when a crop
          // exceeds the viewer's safety limit. Newly reviewed regions must
          // cover every source page within their audited map-level limit.
          expect(paperRegionFor(map.q, n, map.maxCropPages)?.map(region => region.p), task.id)
            .toEqual(expect.arrayContaining(task.sourcePages));
          expect(schemeRegionFor(anchor).map(region => region.p), task.id)
            .toEqual(expect.arrayContaining(task.schemePages));
        }
        expect(task.examTopicIds.length, task.id).toBeGreaterThan(0);
        expect(browseTopicIdsForQuestion(paper, question), task.id)
          .toEqual(expect.arrayContaining(task.examTopicIds));
        for (const topic of task.examTopicIds) {
          if (!feeds.has(topic)) feeds.set(topic, new Set(questionsForTopics('mathematics', [topic])
            .filter(item => item.lang === 'ev')
            .map(item => identity(item.year, item.fileid, item.n))));
          expect(feeds.get(topic)!.has(identity(review.year, review.paperFileid, n)), `${task.id}: ${topic}`).toBe(true);
        }
      }
    });
  }
});
