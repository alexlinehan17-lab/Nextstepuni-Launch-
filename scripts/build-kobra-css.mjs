import fs from 'node:fs';
import path from 'node:path';
import postcss from 'postcss';
import selectorParser from 'postcss-selector-parser';
import ts from 'typescript';

// Keep the purchased motion rules and only the utilities used by these controls.
// Scope the result so Tailwind 4's reset/tokens cannot restyle the Tailwind 3 app.
const directory = 'components/kobra';
const classes = new Set(['dark', 'light', 'command-active-indicator']);
function scan(directory) {
  for (const entry of fs.readdirSync(directory, { withFileTypes: true })) {
    const file = path.join(directory, entry.name);
    if (entry.isDirectory()) {
      if (entry.name === 'navigation') continue;
      scan(file);
      continue;
    }
    if (!file.endsWith('.tsx') && !file.endsWith('.ts')) continue;
    const ast = ts.createSourceFile(
      file,
      fs.readFileSync(file, 'utf8'),
      ts.ScriptTarget.Latest,
      true,
      ts.ScriptKind.TSX,
    );
    function visit(node) {
      if (
        ts.isStringLiteral(node) ||
        ts.isNoSubstitutionTemplateLiteral(node) ||
        ts.isTemplateHead(node) ||
        ts.isTemplateMiddle(node) ||
        ts.isTemplateTail(node)
      ) {
        for (const token of node.text.split(/\s+/)) classes.add(token);
      }
      ts.forEachChild(node, visit);
    }
    visit(ast);
  }
}
scan(directory);
const css = postcss.parse(fs.readFileSync(`${directory}/source.css`, 'utf8'));
// Native utility names must not collide with the app's Tailwind 3 utilities.
// In particular v3 transform and v4 translate otherwise position dialogs twice.
const utilities = new Set();
css.walkAtRules('layer', layer => {
  if (layer.params !== 'utilities') return;
  layer.walkRules(rule => selectorParser(root => root.walkClasses(node => {
    if (node.value !== 'dark' && node.value !== 'light' && !node.value.startsWith('recharts-')) utilities.add(node.value);
  })).processSync(rule.selector));
});
css.walkRules((rule) => {
  if (rule.parent.type === 'atrule' && /keyframes$/.test(rule.parent.name)) return;
  const selectors = rule.selectors.filter((selector) => {
    let needed = true;
    selectorParser((root) =>
      root.walkClasses((node) => {
        if (!classes.has(node.value) && !node.value.startsWith('recharts-')) needed = false;
      }),
    ).processSync(selector);
    return needed;
  });
  if (!selectors.length) {
    rule.remove();
    return;
  }
  rule.selectors = selectors.map((selector) => {
    if (/^(:root|:host|html|body)$/.test(selector)) return '.nsu-kobra';
    if (selector === '.dark') return '.dark .nsu-kobra';
    if (selector === '.light') return '.light .nsu-kobra';
    const isolated = selectorParser(root => root.walkClasses(node => {
      if (utilities.has(node.value)) node.value = `nsuk-${node.value}`;
    })).processSync(selector);
    return `:where(.nsu-kobra) ${isolated.replace(/:root|:host/g, '.nsu-kobra')}`;
  });
});
// Flatten the library layers, retaining their original order. The app's own
// unlayered CSS must not suppress the reviewed control states and utilities.
css.walkAtRules('layer', (rule) => {
  if (rule.nodes) rule.replaceWith(...rule.nodes);
  else rule.remove();
});
const keyframes = new Map();
css.walkAtRules(/keyframes$/, (rule) => {
  keyframes.set(rule.params, `nsuk-${rule.params}`);
  rule.params = `nsuk-${rule.params}`;
});
css.walkDecls((decl) => {
  if (decl.prop === 'animation' || decl.prop === 'animation-name' || decl.prop.startsWith('--')) {
    decl.value = decl.value.replace(/[-\w]+/g, (token) => keyframes.get(token) ?? token);
  }
});
const output = css.toString().replaceAll('--tw-', '--nsuk-tw-');
fs.writeFileSync(`${directory}/lib/utility-classes.ts`,
  `// Generated by scripts/build-kobra-css.mjs.\nexport const utilityClasses = new Set(${JSON.stringify([...utilities].filter(name => classes.has(name)).sort())});\n`);
fs.writeFileSync(
  `${directory}/scoped.css`,
  `/* Generated by scripts/build-kobra-css.mjs. */\n${output}\n`,
);
console.log(`Scoped Kobra CSS: ${Math.round(Buffer.byteLength(output) / 1024)} KiB`);
