def point(text, marks, note=None, kind='point'):
    row = {'kind': kind, 'verbatim': text, 'marks': marks}
    if note:
        row['contextNote'] = note
    return row


def menu(options, steps, note=None):
    if isinstance(options, str):
        options = options.split('|')
    row = point(' / '.join(options), sum(steps), note, 'anyN')
    row['group'] = {'claimMax': len(steps), 'perOption': steps[0], 'options': options}
    if len(set(steps)) > 1:
        row['group']['perOptionSteps'] = steps
    return row


def region(page, start, end, x0=0, x1=1):
    return {'p': page, 'r': [x0, start, x1, end]}


