def crit(sel, marks, **kw):
    return pt(sel, marks, kind='criterion', note=CRIT, **kw)


def amo(marks=4):
    """"apparatus [4] method [4] observation [4]": the scheme names only what earns the marks."""
    return [crit(S('apparatus'), marks), crit(S('method'), marks),
            crit(S('observation'), marks, note_sel=PARTS)]


